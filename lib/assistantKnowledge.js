const compact = (text) => String(text || "").replace(/\s+/g, "");

/** หัวข้อที่ตรงกับคำถาม (เรียงตามจำนวนรูปแบบที่ตรง) — สูงสุด 2 หัวข้อ */
export function matchKnowledge(message, { limit = 2 } = {}) {
  const text = compact(message);
  if (!text) return [];
  return KNOWLEDGE_TOPICS
    .map((topic, index) => {
      const hits = topic.patterns.filter((pattern) => pattern.test(text)).length;
      // หัวข้อทั่วไป (น้ำกำลังขึ้น) มีรูปแบบซ้อนกันหลายแบบ จึงนับสูงสุด 1 ไม่ให้ชนะหัวข้อเฉพาะ
      return { topic, index, score: topic.generic ? Math.min(hits, 1) : hits };
    })
    .filter((item) => item.score > 0)
    .sort((a, b) => (b.topic.urgent === true) - (a.topic.urgent === true) || b.score - a.score
      || (a.topic.generic === true) - (b.topic.generic === true) || a.index - b.index)
    .slice(0, limit)
    .map((item) => item.topic);
}

/** ข้อความความรู้สำหรับส่งให้ AI เป็นข้อเท็จจริงประกอบ */
export function knowledgeFacts(topics = []) {
  return topics.map((topic) => `[${topic.title}]\n${topic.lines.join("\n")}`).join("\n\n");
}

/** คำตอบจากคลังความรู้โดยตรง (ไม่ใช้ AI) */
export function knowledgeAnswer(topics = []) {
  if (!topics.length) return null;
  const [main, extra] = topics;
  const lines = [...main.lines];
  if (extra && !extra.generic) lines.push("", `เรื่อง${extra.title}:`, ...extra.lines.slice(1, 4));
  if (main.kind === "health" || extra?.kind === "health") lines.push("", DISCLAIMER);
  const actions = [...main.actions, ...(extra?.actions || [])].filter((item, index, list) => list.findIndex((other) => other.href === item.href) === index).slice(0, 3);
  return {
    answer: lines.join("\n"),
    actions,
    suggestions: main.suggestions,
    topicId: main.id,
    urgent: Boolean(main.urgent),
    kind: main.kind
  };
}
